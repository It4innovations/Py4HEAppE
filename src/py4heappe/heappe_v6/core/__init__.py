def _to_snake_case(name):
    import re

    step1 = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", step1).lower()


def _patch_legacy_api_methods():
    api_classes = [
        ClusterInformationApi,
        CredentialsApi,
        DataTransferApi,
        DictionaryApi,
        EventsApi,
        FileTransferApi,
        HealthApi,
        JobManagementApi,
        JobReportingApi,
        ManagementApi,
        QSchedulerApi,
        UserAndLimitationManagementApi,
    ]

    for cls in api_classes:
        for attr_name in dir(cls):
            if not attr_name.startswith("heappe_"):
                continue
            if attr_name.endswith("_with_http_info") or attr_name.endswith("_without_preload_content"):
                continue

            original = getattr(cls, attr_name)
            without_preload = getattr(cls, f"{attr_name}_without_preload_content", None)
            if without_preload is None:
                continue

            def _compat(self, *args, __orig=original, __without=without_preload, **kwargs):
                preload_content = kwargs.pop("_preload_content", True)
                mapped_kwargs = {}
                for key, value in kwargs.items():
                    if key.startswith("_") or "_" in key:
                        mapped_kwargs[key] = value
                    else:
                        mapped_kwargs[_to_snake_case(key)] = value
                if preload_content is False:
                    return __without(self, *args, **mapped_kwargs)
                return __orig(self, *args, **mapped_kwargs)

            setattr(cls, attr_name, _compat)


